def detect_language() -> str:
    """Language from LANGUAGE/LC_ALL/LC_MESSAGES/LANG or the OS locale."""
    for var in ("LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(var, "")
        if value and value not in ("C", "POSIX") and not value.startswith("C."):
            code = value.split(":")[0][:2].lower()
            if code in LANGS:
                return code
    try:
        loc = locale.getlocale()[0] or ""
    except ValueError:
        loc = ""
    code = loc[:2].lower()
    if loc.lower().startswith(("portuguese", "pt")):
        return "pt"
    if loc.lower().startswith(("spanish", "es")):
        return "es"
    return code if code in LANGS else "en"


def set_language(language: str) -> str:
    """Select the language (``auto`` detects it). Returns the active code."""
    global _current
    lang = language.lower()[:2] if language and language.lower() != "auto" else detect_language()
    _current = lang if lang in LANGS else "en"
    return _current


def current_language() -> str:
    """Active language code."""
    return _current


def t(message_id: str, /, **kwargs: object) -> str:
    """Translate ``message_id`` and format it with ``kwargs``; unknown ids return the id itself."""
    entry = M.get(message_id)
    if entry is None:
        return message_id
    text = entry[LANGS.index(_current)] or entry[0]
    return text.format(**kwargs) if kwargs else text
